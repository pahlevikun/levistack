    out.append("| Motion | %s | %s |\n" % (r["motion"], lib["motion"][r["motion"]]["describe"]))
    out.append("| Signature | %s | %s |\n" % (", ".join(r["signatures"]), " ".join(lib["signatures"][s]["describe"] for s in r["signatures"])))
    out.append("| Density, ground, contrast | %s, %s, %s | From the moods. |\n\n" % (r["density"], r["ground"], r["contrast"]))
    fails = [c for c in t["checks"] if not c["pass"]]
    out.append("## Contrast checks\n\n%d checks, %d failing.\n\n| Mode | Pair | Ratio | Need | APCA Lc | Result |\n|---|---|---:|---:|---:|---|\n" % (len(t["checks"]), len(fails)))
    for c in t["checks"]:
        out.append("| %s | %s | %.2f | %.1f | %.0f | %s |\n" % (c["mode"], c["pair"], c["ratio"], c["need"], abs(c["apca"]), "pass" if c["pass"] else "**FAIL**"))
    out.append("\nAPCA Lc is advisory. As a rule of thumb, body text wants Lc 75 or more and large text Lc 60 or more.\n\n")
    out.append("## Platform checks\n\n| Platform | Check | Value | Need | Result |\n|---|---|---:|---:|---|\n")
    for c in t["platforms"]["checks"]:
        out.append("| %s | %s | %s | %s | %s |\n" % (c["platform"], c["check"], c["value"], c["need"], "pass" if c["pass"] else "**FAIL**"))
    out.append("\n")
    out.append("## Palette names\n\n| Role | Step 500 | Nearest plain name |\n|---|---|---|\n")
    for role in ("primary", "secondary", "tertiary", "neutral"):
        hx = t["palettes"][role][500]
        out.append("| %s | %s | %s |\n" % (role, hx, names.describe(hx)))
    out.append("\n")
    out.append("## Notes\n\n" + ("\n".join("- " + n for n in t["notes"]) if t["notes"] else "- None.") + "\n")
    return "".join(out)



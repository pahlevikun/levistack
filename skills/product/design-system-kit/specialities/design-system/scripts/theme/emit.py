def typography_block(t):
    v, s = t["type"]["voice"], t["type"]["sizes"]
    dw, bw, lw = v["weights"]
    dt, lt = v["tracking"]

    def entry(family, size, weight, lh, tracking=0):
        e = {"fontFamily": family, "fontSize": px(size), "fontWeight": weight, "lineHeight": lh}
        if tracking:
            e["letterSpacing"] = "%gem" % tracking
        return e
    return {
        "display-lg": entry(v["display"], s["5xl"], dw, 1.05, dt), "display-md": entry(v["display"], s["4xl"], dw, 1.1, dt),
        "headline-lg": entry(v["display"], s["3xl"], dw, 1.15, dt), "headline-md": entry(v["display"], s["2xl"], dw, 1.2, dt),
        "title-lg": entry(v["display"], s["xl"], dw, 1.25, dt / 2), "title-md": entry(v["body"], s["lg"], lw, 1.3),
        "body-lg": entry(v["body"], s["lg"], bw, v["lh"]), "body-md": entry(v["body"], s["base"], bw, v["lh"]), "body-sm": entry(v["body"], s["sm"], bw, v["lh"]),
        "label-md": entry(v["body"], s["sm"], lw, 1.2, lt), "label-sm": entry(v["body"], s["xs"], lw, 1.2, lt),
        "code": entry(v["mono"], round(s["base"] * 0.95 * 2) / 2, 400, 1.5),
    }


def yaml_dump(obj, indent=0):
    pad = "  " * indent
    lines = []
    for k, val in obj.items():
        key = '"%s"' % k if (k[:1].isdigit() or ":" in k) else k
        if isinstance(val, dict):
            lines.append("%s%s:" % (pad, key))
            lines.append(yaml_dump(val, indent + 1))
        elif isinstance(val, (int, float)) and not isinstance(val, bool):
            lines.append("%s%s: %s" % (pad, key, ("%g" % val)))
        else:
            lines.append('%s%s: "%s"' % (pad, key, val) if not str(val).startswith('"') else "%s%s: %s" % (pad, key, val))
    return "\n".join(lines)



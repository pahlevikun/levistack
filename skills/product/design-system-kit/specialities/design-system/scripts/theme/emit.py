from oklch import hex_to_oklch, hue_name

SERIFS = {"Fraunces", "Newsreader", "Source Serif 4", "Playfair Display", "Instrument Serif", "Lora"}
MONOS = {"Space Mono", "JetBrains Mono", "IBM Plex Mono"}
STEP_KEYS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950]


def stack(family):
    if family in MONOS:
        return '"%s", ui-monospace, "SF Mono", Menlo, Consolas, monospace' % family
    if family in SERIFS:
        return '"%s", Georgia, "Times New Roman", serif' % family
    return '"%s", system-ui, -apple-system, "Segoe UI", Roboto, sans-serif' % family


def px(n):
    n = float(n)
    return "%dpx" % n if n == int(n) else "%.1fpx" % n


def rem(n):
    return ("%.3f" % (float(n) / 16)).rstrip("0").rstrip(".") + "rem"


def ease(c):
    return "cubic-bezier(%s)" % ", ".join(("%g" % v) for v in c)


def color_name(h):
    L, C, H = hex_to_oklch(h)
    if C < 0.03:
        warm = H < 120 or H > 330
        tone = "White" if L > 0.95 else "Ivory" if (L > 0.88 and warm) else "Mist" if L > 0.88 else "Gray" if L > 0.55 else "Charcoal" if L > 0.28 else "Ink"
        return ("Warm " if warm and tone in ("Gray", "Charcoal") else "Cool " if tone in ("Gray", "Charcoal") else "") + tone
    light = "Pale" if L > 0.9 else "Soft" if L > 0.78 else "Mid" if L > 0.6 else "Deep" if L > 0.42 else "Dark"
    muted = "Muted " if C < 0.06 else ""
    return "%s %s%s" % (light, muted, hue_name(H))


def semantic_css(tokens, indent="  "):
    return "".join("%s--color-%s: %s;\n" % (indent, k, v) for k, v in tokens.items())


def theme_css(t):
    r, v = t["recipe"], t["type"]["voice"]
    light, dark = t["modes"]["light"], t["modes"]["dark"]
    default_dark = r["ground"] == "dark"
    out = ["/* %s: generated by design-system-kit theme.py. Edit the recipe or tokens.json, then rebuild. */\n" % r["name"]]
    out.append(":root {\n  color-scheme: light dark;\n")
    for role, rmp in t["palettes"].items():
        for s in STEP_KEYS:
            out.append("  --palette-%s-%d: %s;\n" % (role, s, rmp[s]))
    out.append("\n  --font-display: %s;\n  --font-body: %s;\n  --font-mono: %s;\n" % (stack(v["display"]), stack(v["body"]), stack(v["mono"])))
    out.append("  --weight-display: %d;\n  --weight-body: %d;\n  --weight-label: %d;\n" % tuple(v["weights"]))
    out.append("  --tracking-display: %gem;\n  --tracking-label: %gem;\n  --line-height-body: %g;\n" % (v["tracking"][0], v["tracking"][1], v["lh"]))
    for k, size in t["type"]["sizes"].items():
        val = rem(size) if k not in ("3xl", "4xl", "5xl") else "clamp(%s, %.2fvw + 1rem, %s)" % (rem(size * 0.7), size / 16 * 1.4, rem(size))
        out.append("  --text-%s: %s;\n" % (k, val))
    for k, size in t["space"].items():
        out.append("  --space-%s: %s;\n" % (k, rem(size)))
    for k, size in t["radius"].items():
        out.append("  --radius-%s: %s;\n" % (k, px(size)))
    out.append("  --border-width: %dpx;\n  --control-pad-y: %s;\n  --control-pad-x: %s;\n  --control-height: %dpx;\n  --focus-ring-width: %dpx;\n" % (t["border"], px(t["pad"][0]), px(t["pad"][1]), t["control_height"], t["focus_ring"]))
    m = t["motion"]
    out.append("  --dur-fast: %dms;\n  --dur-base: %dms;\n  --dur-slow: %dms;\n" % tuple(m["dur"]))
    out.append("  --ease-out: %s;\n  --ease-in-out: %s;\n  --ease-in: %s;\n" % (ease(m["ease"]["out"]), ease(m["ease"]["inout"]), ease(m["ease"]["in"])))
    out.append("  --motion-distance: %dpx;\n  --press-scale: %g;\n  --stagger: %dms;\n" % (m["distance"], m["press"], m["stagger"]))
    for i, c in enumerate(t["chart"]["light"], 1):
        out.append("  --chart-%d: %s;\n" % (i, c))
    first, second = (dark, light) if default_dark else (light, dark)
    out.append("\n" + semantic_css(first))
    shadow = t["elevation"]["shadow_dark" if default_dark else "shadow_light"]
    out.append(shadow_vars(t, shadow, default_dark))
    out.append("}\n\n")
    alt_name = "light" if default_dark else "dark"
    alt_shadow = t["elevation"]["shadow_light" if default_dark else "shadow_dark"]
    out.append(':root[data-theme="%s"] {\n%s%s}\n\n' % (alt_name, semantic_css(second), shadow_vars(t, alt_shadow, not default_dark)))
    if not default_dark:
        out.append('@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n%s%s  }\n}\n\n' % (semantic_css(dark, "    "), shadow_vars(t, t["elevation"]["shadow_dark"], True, "    ")))
        out.append(':root[data-theme="dark"] {\n%s}\n\n' % "")
    out.append("@media (prefers-reduced-motion: reduce) {\n  :root { --dur-fast: 1ms; --dur-base: 1ms; --dur-slow: 1ms; --motion-distance: 0px; --press-scale: 1; --stagger: 0ms; }\n}\n")
    return "".join(out).replace(':root[data-theme="dark"] {\n}\n\n', "")


def platforms_css(t):
    """One override block per extra platform: [data-platform="tv"] { ... }. The lead platform is in theme.css."""
    ids = t["platforms"]["ids"]
    out = ["/* Platform overrides. Set data-platform on <html>. The lead platform (%s) is already in theme.css. */\n" % ids[0]]
    for pid in ids:
        sc = t["platforms"]["scaled"][pid]
        sel = ':root[data-platform="%s"]' % pid
        out.append("%s {\n" % sel)
        for k, size in sc["sizes"].items():
            val = rem(size) if k not in ("3xl", "4xl", "5xl") else "clamp(%s, %.2fvw + 1rem, %s)" % (rem(size * 0.7), size / 16 * 1.4, rem(size))
            out.append("  --text-%s: %s;\n" % (k, val))
        for k, size in sc["space"].items():
            out.append("  --space-%s: %s;\n" % (k, rem(size)))
        out.append("  --control-height: %dpx;\n  --control-pad-y: %s;\n  --control-pad-x: %s;\n  --focus-ring-width: %dpx;\n" % (sc["control_height"], px(sc["pad"][0]), px(sc["pad"][1]), sc["focus_ring"]))
        m = sc["motion"]
        out.append("  --dur-fast: %dms;\n  --dur-base: %dms;\n  --dur-slow: %dms;\n  --motion-distance: %dpx;\n}\n\n" % (m["dur"][0], m["dur"][1], m["dur"][2], m["distance"]))
    return "".join(out)


def shadow_vars(t, rgb, dark, indent="  "):
    levels = t["elevation"]["levels"]
    out = []
    for i, lv in enumerate(levels, 1):
        a = {1: 0.10, 2: 0.14, 3: 0.20}[i] * (2.2 if dark else 1)
        col = "rgb(%s / %.2f)" % (rgb, min(a, 0.7))
        out.append("%s--shadow-%d: %s;\n" % (indent, i, lv.replace("{shadow}", col).replace("{ink}", t["modes"]["light"]["text"])))
    return "".join(out)


def tailwind_css(t):
    names = list(t["modes"]["light"].keys())
    out = ["/* Tailwind v4: import after theme.css. Semantic names map to the CSS variables. */\n@theme inline {\n"]
    for n in names:
        out.append("  --color-%s: var(--color-%s);\n" % (n, n))
    for k in t["type"]["sizes"]:
        out.append("  --text-%s: var(--text-%s);\n" % (k, k))
    for k in t["radius"]:
        out.append("  --radius-%s: var(--radius-%s);\n" % (k, k))
    out.append("  --font-display: var(--font-display);\n  --font-sans: var(--font-body);\n  --font-mono: var(--font-mono);\n")
    for i in (1, 2, 3):
        out.append("  --shadow-%d: var(--shadow-%d);\n" % (i, i))
    out.append("}\n")
    return "".join(out)


def tokens_json(t):
    def col(h):
        return {"$value": h, "$type": "color"}
    prim = {"color": {role: {str(s): col(h) for s, h in rmp.items()} for role, rmp in t["palettes"].items()}}
    prim["spacing"] = {k: {"$value": px(v), "$type": "dimension"} for k, v in t["space"].items()}
    prim["fontSize"] = {k: {"$value": px(v), "$type": "dimension"} for k, v in t["type"]["sizes"].items()}
    prim["radius"] = {k: {"$value": px(v), "$type": "dimension"} for k, v in t["radius"].items()}
    m = t["motion"]
    prim["duration"] = {k: {"$value": "%dms" % d, "$type": "duration"} for k, d in zip(("fast", "normal", "slow"), m["dur"])}
    prim["easing"] = {k: {"$value": ease(m["ease"][k]), "$type": "cubicBezier"} for k in ("out", "inout", "in")}
    prim["shadow"] = {str(i + 1): {"$value": lv.replace("{shadow}", "rgb(%s / .14)" % t["elevation"]["shadow_light"]).replace("{ink}", t["modes"]["light"]["text"]), "$type": "shadow"} for i, lv in enumerate(t["elevation"]["levels"])}
    sem = {"color": {k: col(v) for k, v in t["modes"]["light"].items()}}
    darksem = {"semantic": {"color": {k: col(v) for k, v in t["modes"]["dark"].items()}}}
    comp = {
        "button": {"bg": {"$value": "{semantic.color.primary}", "$type": "color"}, "fg": {"$value": "{semantic.color.on-primary}", "$type": "color"},
                   "hover-bg": {"$value": "{semantic.color.primary-hover}", "$type": "color"}, "radius": {"$value": "{primitive.radius.md}", "$type": "dimension"}},
        "input": {"bg": {"$value": "{semantic.color.surface}", "$type": "color"}, "border": {"$value": "{semantic.color.border-strong}", "$type": "color"},
                  "focus-ring": {"$value": "{semantic.color.focus-ring}", "$type": "color"}, "radius": {"$value": "{primitive.radius.md}", "$type": "dimension"}},
        "card": {"bg": {"$value": "{semantic.color.surface-raised}", "$type": "color"}, "border": {"$value": "{semantic.color.border}", "$type": "color"},
                 "radius": {"$value": "{primitive.radius.lg}", "$type": "dimension"}},
    }
    return json.dumps({"$schema": "https://design-tokens.org/schema.json", "$name": t["recipe"]["name"], "primitive": prim, "semantic": sem, "component": comp, "dark": darksem,
                       "recipe": t["recipe"]}, indent=2)



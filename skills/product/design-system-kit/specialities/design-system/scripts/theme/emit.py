def design_md(t, lib):
    r = t["recipe"]
    light, dark = t["modes"]["light"], t["modes"]["dark"]
    colors = {name: light[key] for name, key in LIGHT_KEYS}
    key_of = dict(LIGHT_KEYS)
    for name in DARK_KEYS:
        colors[name + "-dark"] = dark[key_of[name]]
    typo = typography_block(t)
    rounded = {k: px(v) for k, v in t["radius"].items()}
    spacing = {k: px(v) for k, v in t["space"].items()}
    domain_labels = ", ".join(lib["domains"][d]["label"].lower() for d in r["domains"]) or "a general product"
    lead = r["name"].split()[0].lower()
    mood_words = []
    for m in r["moods"]:
        mood_words += [w for w in lib["moods"][m]["words"][:2] if w.split()[0].lower() != lead]
    voice, shape, motion = lib["voices"][r["voice"]], lib["shapes"][r["shape"]], lib["motion"][r["motion"]]
    sig_text = " ".join(lib["signatures"][s]["describe"] for s in r["signatures"])
    avoid = []
    for d in r["domains"]:
        avoid += lib["domains"][d].get("avoid", [])
    notes = " ".join(lib["domains"][d]["note"] for d in r["domains"])

    fm = {
        "version": "alpha", "name": r["name"],
        "description": "%s design for %s. %s." % (", ".join(mood_words[:3]).capitalize(), domain_labels, lib["harmonies"][r["harmony"]]["describe"].capitalize()),
        "colors": colors, "typography": typo, "rounded": rounded, "spacing": spacing,
    }
    out = ["---\n", yaml_dump(fm), "\n---\n\n"]
    out.append("# %s\n\n## Overview\n\n" % r["name"])
    out.append("%s is a %s system for %s. %s\n\n" % (r["name"], ", ".join(mood_words[:4]), domain_labels, notes))
    out.append("**Signature.** %s\n\n" % sig_text)
    out.append("**Density.** %s. **Default ground.** %s, with a full %s mode.\n\n" % (r["density"].capitalize(), r["ground"], "light" if r["ground"] == "dark" else "dark"))

    out.append("## Colors\n\n")
    out.append("The primary is %s (`%s`). It is the only color that asks for action, so use it for one main action per screen. The accent family follows a %s harmony: %s.\n\n" % (color_name(light["primary"]), light["primary"], r["harmony"], lib["harmonies"][r["harmony"]]["describe"]))
    out.append("- **Primary** %s `%s`: main actions, selected state, links on tint.\n" % (color_name(light["primary"]), light["primary"]))
    out.append("- **Secondary** %s `%s`: supporting actions and illustration.\n" % (color_name(light["secondary"]), light["secondary"]))
    out.append("- **Tertiary** %s `%s`: small highlights only. Use it for at most one thing per screen.\n" % (color_name(light["tertiary"]), light["tertiary"]))
    out.append("- **Neutral ground** %s `%s` on %s. The neutral is %s.\n" % (color_name(light["background"]), light["background"], "surfaces", r["neutral"]["describe"]))
    out.append("- **Status** success `%s`, warning `%s`, error `%s`, info `%s`. Always pair them with an icon or a label.\n\n" % (light["success"], light["warning"], light["danger"], light["info"]))
    out.append("Use roughly 60%% neutral, 30%% surface and brand tints, 10%% saturated color. Dark mode is designed, not inverted: the ground is %s (`%s`) and the primary is lifted to `%s` so it stays visible.\n\n" % (color_name(dark["background"]).lower(), dark["background"], dark["primary"]))
    out.append("Every text pair passes WCAG 2.x AA (4.5:1) and every control edge, focus ring and status color passes 3:1 against its ground, in both modes. Run `theme.py check` after any edit.\n\n")

    out.append("## Typography\n\n%s Headings use **%s**, body text uses **%s**, code uses **%s**.\n\n" % (voice["describe"], voice["display"], voice["body"], voice["mono"]))
    out.append("The scale uses a ratio of %g from a %dpx base. Display sizes should be fluid. Labels are %s and tracked %g em. Body line height is %g.\n\n" % (voice["scale"], voice["base"], "set in capitals" if voice["case"] == "upper" else "set in sentence case", voice["tracking"][1], voice["lh"]))

    out.append("## Layout\n\nSpacing uses %s %s scale: %s. Controls are %dpx tall. Content columns stay between 60 and 75 characters for reading text. %s\n\n" % ("an" if r["density"][0] in "aeiou" else "a", r["density"], ", ".join(px(v) for v in t["space"].values()), t["control_height"], "Use generous gutters and let sections breathe." if r["density"] == "airy" else "Pack information tightly, but keep rows tall enough to tap." if r["density"] == "dense" else "Use the middle of the scale for most gaps."))
    for pid in t["platforms"]["ids"]:
        pl, sc = t["platforms"]["profiles"][pid], t["platforms"]["scaled"][pid]
        out.append("**Platform: %s.** Input: %s. Body text %dpx, controls %dpx, smallest target %dpx, focus ring %dpx. %s %s\n\n" % (pl["label"], pl["input"], sc["sizes"]["base"], sc["control_height"], pl["min_target"], sc["focus_ring"], pl["safe_area"], " ".join(pl["notes"][:3])))

    out.append("## Elevation & Depth\n\n%s\n\n" % t["elevation"]["describe"])
    out.append("## Shapes\n\n%s Radii: %s. Default control border: %dpx.\n\n" % (shape["describe"], ", ".join("%s %s" % (k, v) for k, v in rounded.items()), t["border"]))

    out.append("## Components\n\n```yaml\ncomponents:\n%s\n```\n\n" % yaml_dump(components_block(t), 1))
    out.append("Buttons are %dpx tall with `%s` radius. Cards sit on `surface-raised`. Inputs use the stronger outline so their edge is always visible. Focus rings are %dpx wide, `%s` in light mode and `%s` in dark mode, and are never removed.\n\n" % (t["control_height"], rounded["md"], t["focus_ring"], light["focus-ring"], dark["focus-ring"]))

    out.append("## Motion\n\n%s Durations are %s ms. Entrances travel %dpx. Presses scale to %g. Siblings stagger by %d ms. When the user asks for reduced motion, durations drop to near zero and movement is removed, but state changes still show.\n\n" % (motion["describe"], " / ".join(str(d) for d in motion["dur"]), motion["distance"], motion["press"], motion["stagger"]))


"""Bind a built theme (tokens.json) to one named stack. Standard library only.

The binding maps semantic roles, not raw palette steps, so a theme change repoints the roles and no
component changes. Output is generated source. Do not edit it by hand: rebuild from tokens.json.

Stacks: flutter, compose, swiftui, react-native, vue. For plain CSS and Tailwind, theme.py build
already writes theme.css and tailwind-theme.css.
"""


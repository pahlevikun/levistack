def camel(key):
    parts = key.split("-")
    return parts[0] + "".join(p.capitalize() for p in parts[1:])


def load(path):
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    light = {k: v["$value"] for k, v in data["semantic"]["color"].items()}
    dark = {k: v["$value"] for k, v in data["dark"]["semantic"]["color"].items()}
    return data.get("$name", "Theme"), light, dark


def argb(h):
    return "0xFF" + h.lstrip("#").upper()


def flutter(name, light, dark):
    out = ["// " + HEADER, "// Roles: background to surfaceContainerLowest, surface to surfaceContainer and Low, surface-raised to surfaceContainerHigh and Highest and surfaceBright.",
           "// surface-sunken has no Material slot, read it with context.appColors.surfaceSunken. inversePrimary and scrim are set below.",
           "// Theme name: " + name, "import 'package:flutter/material.dart';", ""]
    for mode, table in (("light", light), ("dark", dark)):
        out.append("const ColorScheme %sColorScheme = ColorScheme(" % mode)
        out.append("  brightness: Brightness.%s," % mode)
        for role, key in FLUTTER_SCHEME:
            out.append("  %s: Color(%s)," % (role, argb(table[key])))
        other = dark if mode == "light" else light
        out.append("  inversePrimary: Color(%s)," % argb(other["primary"]))
        out.append("  scrim: Color(0xFF000000),")
        out.append(");")
        out.append("")
    out += ["/// Roles that Material's ColorScheme has no slot for. Read them with context.appColors.", "@immutable", "class AppColors extends ThemeExtension<AppColors> {",
            "  const AppColors({"]
    out += ["    required this.%s," % camel(k) for k in EXTRA_ROLES]
    out += ["  });", ""]
    out += ["  final Color %s;" % camel(k) for k in EXTRA_ROLES]
    out += ["", "  @override", "  AppColors copyWith({"]
    out += ["    Color? %s," % camel(k) for k in EXTRA_ROLES]
    out += ["  }) {", "    return AppColors("]
    out += ["      %s: %s ?? this.%s," % (camel(k), camel(k), camel(k)) for k in EXTRA_ROLES]
    out += ["    );", "  }", "", "  @override", "  AppColors lerp(ThemeExtension<AppColors>? other, double t) {", "    if (other is! AppColors) return this;", "    return AppColors("]
    out += ["      %s: Color.lerp(%s, other.%s, t)!," % (camel(k), camel(k), camel(k)) for k in EXTRA_ROLES]
    out += ["    );", "  }", "}", ""]
    for mode, table in (("light", light), ("dark", dark)):
        out.append("const AppColors %sAppColors = AppColors(" % mode)
        out += ["  %s: Color(%s)," % (camel(k), argb(table[k])) for k in EXTRA_ROLES]
        out += [");", ""]
    for mode, table in (("light", light), ("dark", dark)):
        out += ["ThemeData %sTheme() => ThemeData(" % mode, "      useMaterial3: true,", "      colorScheme: %sColorScheme," % mode,
                "      scaffoldBackgroundColor: Color(%s)," % argb(table["background"]), "      extensions: const [%sAppColors]," % mode, "    );", ""]
    out += ["extension AppColorsContext on BuildContext {", "  AppColors get appColors => Theme.of(this).extension<AppColors>()!;", "}", "",
            "// Use: MaterialApp(theme: lightTheme(), darkTheme: darkTheme(), themeMode: ThemeMode.system).",
            "// Read colors from Theme.of(context).colorScheme or context.appColors. Never write a hex in a widget."]
    return {"app_theme.dart": "\n".join(out) + "\n"}


def compose(name, light, dark):
    out = ["// " + HEADER, "// Theme name: " + name, "// Needs Material 3 version 1.2 or later (surface container slots). Every slot a scheme can hold is set, so no default purple color is left.",
           "// Change the package to your own.", "package app.theme", "",
           "import androidx.compose.material3.darkColorScheme", "import androidx.compose.material3.lightColorScheme",
           "import androidx.compose.runtime.Immutable", "import androidx.compose.runtime.staticCompositionLocalOf",
           "import androidx.compose.ui.graphics.Color", ""]
    for mode, table in (("Light", light), ("Dark", dark)):
        out.append("val %sColors = %sColorScheme(" % (mode, mode.lower()))
        out += ["    %s = Color(%s)," % (role, argb(table[key])) for role, key in COMPOSE_SCHEME]
        other = dark if mode == "Light" else light
        out += ["    inversePrimary = Color(%s)," % argb(other["primary"]), "    scrim = Color(0xFF000000),", ")", ""]
    out += ["/** Roles that ColorScheme has no slot for. Read them with LocalExtraColors.current. */", "@Immutable", "data class ExtraColors("]
    out += ["    val %s: Color," % camel(k) for k in EXTRA_ROLES]
    out += [")", ""]
    for mode, table in (("Light", light), ("Dark", dark)):
        out.append("val %sExtraColors = ExtraColors(" % mode)
        out += ["    %s = Color(%s)," % (camel(k), argb(table[k])) for k in EXTRA_ROLES]
        out += [")", ""]
    out += ["val LocalExtraColors = staticCompositionLocalOf { LightExtraColors }", "",
            "// Wrap your content: MaterialTheme(colorScheme = if (dark) DarkColors else LightColors) {",
            "//     CompositionLocalProvider(LocalExtraColors provides if (dark) DarkExtraColors else LightExtraColors) { content() } }",
            "// On Android 12 and later you may start from dynamicLightColorScheme(context) and keep these as the static fallback.",
            "// Read colors from MaterialTheme.colorScheme or LocalExtraColors.current. Never write a hex in a composable."]
    return {"AppColors.kt": "\n".join(out) + "\n"}


def swiftui(name, light, dark):
    keys = ["background", "surface", "surface-raised", "surface-sunken", "border", "border-strong", "text", "text-muted", "text-subtle", "link", "focus-ring",
            "primary", "on-primary", "primary-hover", "primary-pressed", "primary-subtle", "on-primary-subtle",
            "secondary", "on-secondary", "secondary-subtle", "on-secondary-subtle", "tertiary", "on-tertiary",
            "danger", "on-danger", "danger-subtle", "on-danger-subtle", "success", "on-success", "success-subtle", "on-success-subtle",
            "warning", "on-warning", "warning-subtle", "on-warning-subtle", "info", "on-info", "info-subtle", "on-info-subtle"]
    swift = lambda h: "0x" + h.lstrip("#").upper()  # noqa: E731
    out = ["// " + HEADER, "// Theme name: " + name, "import SwiftUI", "", "#if canImport(UIKit)", "import UIKit", "#elseif canImport(AppKit)", "import AppKit", "#endif", "",
           "extension Color {", "    init(hex: UInt32) {",
           "        self.init(.sRGB, red: Double((hex >> 16) & 0xFF) / 255, green: Double((hex >> 8) & 0xFF) / 255, blue: Double(hex & 0xFF) / 255, opacity: 1)", "    }", "",
           "    /// A color that follows the system light or dark appearance. For Increased Contrast variants, keep the colors in an asset catalog instead.",
           "    init(light: UInt32, dark: UInt32) {", "#if canImport(UIKit)",
           "        self.init(UIColor { trait in UIColor(Color(hex: trait.userInterfaceStyle == .dark ? dark : light)) })", "#else",
           "        self.init(NSColor(name: nil) { appearance in",
           "            let isDark = appearance.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua",
           "            return NSColor(Color(hex: isDark ? dark : light))", "        })", "#endif", "    }", "}", "",
           "/// Semantic colors. Use these in views. Never write a hex in a view.", "enum AppColor {"]
    for k in keys:
        out.append("    static let %s = Color(light: %s, dark: %s)" % (camel(k), swift(light[k]), swift(dark[k])))
    out += ["}", "", "// Set the app tint once: .tint(AppColor.primary). Honor the system Dark Mode setting. Test Increased Contrast and Dynamic Type too."]
    return {"AppColors.swift": "\n".join(out) + "\n"}


def react_native(name, light, dark):
    keys = sorted(set(light) & set(dark))
    out = ["// " + HEADER, "// Theme name: " + name, "import { useColorScheme } from 'react-native';", "", "export type Colors = {"]
    out += ["  %s: string;" % camel(k) for k in keys]
    out += ["};", ""]
    for mode, table in (("light", light), ("dark", dark)):
        out.append("export const %sColors: Colors = {" % mode)
        out += ["  %s: '%s'," % (camel(k), table[k].upper()) for k in keys]
        out += ["};", ""]
    out += ["/** Follows the system appearance. For a manual override, keep the choice in your own store and pick the object yourself. */",
            "export function useColors(): Colors {", "  return useColorScheme() === 'dark' ? darkColors : lightColors;", "}", "",
            "// Read colors with const c = useColors(). Never write a hex in a component."]
    return {"colors.ts": "\n".join(out) + "\n"}


def vue(name, light, dark):
    out = ["// " + HEADER, "// Theme name: " + name, "// Pair this with theme.css from theme.py build. Colors live in CSS variables, this file only switches the mode.",
           "import { ref, watchEffect } from 'vue';", "", "export type ThemeMode = 'system' | 'light' | 'dark';", "const KEY = 'theme-mode';", "",
           "function readStored(): ThemeMode {", "  try {", "    const v = localStorage.getItem(KEY);", "    return v === 'light' || v === 'dark' ? v : 'system';",
           "  } catch {", "    return 'system';", "  }", "}", "", "const mode = ref<ThemeMode>(readStored());", "",
           "export function useTheme() {", "  watchEffect(() => {", "    const root = document.documentElement;",
           "    if (mode.value === 'system') root.removeAttribute('data-theme');", "    else root.setAttribute('data-theme', mode.value);",
           "    try {", "      if (mode.value === 'system') localStorage.removeItem(KEY);", "      else localStorage.setItem(KEY, mode.value);", "    } catch {", "      /* storage can be blocked */", "    }", "  });",
           "  return { mode };", "}", "",
           "// In Nuxt a color-mode module works too. Keep one switching mechanism only: the data-theme attribute here, or a class, not both."]
    return {"useTheme.ts": "\n".join(out) + "\n"}


STACKS = {"flutter": flutter, "compose": compose, "swiftui": swiftui, "react-native": react_native, "vue": vue}


def bind(tokens_path, stack, out_dir):
    if stack not in STACKS:
        raise ValueError("unknown stack '%s'. Choose one of: %s" % (stack, ", ".join(sorted(STACKS))))
    name, light, dark = load(tokens_path)
    missing = [k for k in ("background", "surface", "text", "primary", "on-primary", "danger") if k not in light or k not in dark]
    if missing:
        raise ValueError("tokens.json lacks roles: %s" % ", ".join(missing))
    files = STACKS[stack](name, light, dark)
    os.makedirs(out_dir, exist_ok=True)
    written = []
    for fname, text in files.items():
        path = os.path.join(out_dir, fname)
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        written.append(path)
    return written
